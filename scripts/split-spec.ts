// Splits docs/source/master_head.md and docs/source/BLUEPRINT.md into docs/spec/*.md
// verbatim (one added header line + one blank line per file), then regenerates
// docs/spec/INDEX.md. Re-runnable: output is deterministic. DECISIONS.md is hand-written
// and never touched here.
//
// Usage: pnpm spec:split

import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  INDEX_COPIED_SECTIONS,
  ROOT,
  SOURCES,
  SPEC_DIR,
  type Chunk,
  chunkSource,
  countLines,
  extractSection,
  headerLine,
} from "./spec-config.ts";

const outDir = resolve(ROOT, SPEC_DIR);
mkdirSync(outDir, { recursive: true });

const written: { chunk: Chunk; lines: number }[] = [];

for (const cfg of SOURCES) {
  for (const chunk of chunkSource(cfg)) {
    const content = `${headerLine(chunk)}\n\n${chunk.body}`;
    writeFileSync(resolve(outDir, chunk.part.file), content, "utf8");
    written.push({ chunk, lines: countLines(content) });
    console.log(`wrote ${SPEC_DIR}/${chunk.part.file} (${countLines(content)} lines)`);
  }
}

// ---- INDEX.md ----
const esc = (s: string) => s.replace(/\|/g, "\\|");
const rows = written.map(
  ({ chunk, lines }) =>
    `| [${chunk.part.file}](${chunk.part.file}) | ${esc(chunk.part.contents)} | ${lines} | ${esc(chunk.part.readWhen)} |`,
);

const copied = INDEX_COPIED_SECTIONS.map((s) => extractSection(s.source, s.heading).replace(/\s*$/, ""));

const index = [
  "# SaferStreets spec index",
  "",
  "Generated by `pnpm spec:split` from `docs/source/`. Do not edit by hand; edit the sources and re-run. `pnpm spec:verify` checks that the split is lossless and that the line counts below are current.",
  "",
  "Read only the sections your prompt names. Section numbers (A2, B3, 2C, S12, 7.4) map to files as follows: `0.x` -> 00-instructions, `A*` -> A-design, `B*` -> B-backend, Appendix section N -> appendix-NN-*.",
  "",
  "## Files",
  "",
  "| File | Contents | Lines | Read when |",
  "|---|---|---|---|",
  ...rows,
  "| [DECISIONS.md](DECISIONS.md) | Conflicts between master_head and BLUEPRINT with the winning choice (hand-written) | see file | Whenever an appendix file and Part A/B seem to disagree |",
  "| INDEX.md | This file | n/a | Start of every prompt |",
  "",
  "Line counts include the one-line source header and the blank line after it.",
  "",
  "## Precedence and superseded decisions (copied verbatim from master_head.md)",
  "",
  ...copied.flatMap((c) => [c, ""]),
].join("\n");

writeFileSync(resolve(outDir, "INDEX.md"), index, "utf8");
console.log(`wrote ${SPEC_DIR}/INDEX.md`);
