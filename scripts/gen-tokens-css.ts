// Generates apps/web/src/design/tokens.generated.css from apps/web/src/design/tokens.ts.
// globals.css imports it, so tokens.ts stays the single source of colour values.
// Usage: pnpm tokens:css   (a web test fails if the committed file is stale)

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  breakpoints,
  focusRing,
  lightColors,
  motion,
  radii,
  shadows,
  typeScale,
} from "../apps/web/src/design/tokens.ts";

export function buildTokensCss(): string {
  const out: string[] = [];
  out.push("/* GENERATED by `pnpm tokens:css` from src/design/tokens.ts. Do not edit. */", "");

  out.push("@theme {");
  out.push("  /* The default Tailwind palette, radii, shadows, sizes and breakpoints are replaced, not extended. */");
  out.push("  --color-*: initial;", "  --radius-*: initial;", "  --shadow-*: initial;", "  --text-*: initial;");
  out.push("  --breakpoint-*: initial;", "  --spacing: 4px;", "");
  for (const [k, v] of Object.entries(lightColors)) out.push(`  --color-${k}: ${v};`);
  out.push("");
  for (const [k, v] of Object.entries(radii)) out.push(`  --radius-${k}: ${v};`);
  out.push("");
  out.push(`  --shadow-hover: ${shadows.hover};`, `  --shadow-popover: ${shadows.popover};`);
  out.push(`  --shadow-focus: ${focusRing.glow};`, "");
  for (const [k, v] of Object.entries(breakpoints)) out.push(`  --breakpoint-${k}: ${v}px;`);
  out.push("");
  for (const [k, v] of Object.entries(typeScale)) {
    out.push(`  --text-${k}: ${v.desktop.size}px;`, `  --text-${k}--line-height: ${v.desktop.line}px;`);
  }
  out.push("  --font-display: var(--font-plus-jakarta), ui-sans-serif, system-ui, sans-serif;");
  out.push("  --font-body: var(--font-inter), ui-sans-serif, system-ui, sans-serif;");
  out.push(
    `  --ease-out: ${motion.easing};`,
    `  --duration-fast: ${motion.fast};`,
    `  --duration-sheet: ${motion.sheet};`,
  );
  out.push("}", "");

  out.push(":root {");
  out.push(`  --overlay: ${shadows.overlay};`);
  out.push(
    `  --focus-outline: ${focusRing.outline};`,
    `  --focus-offset: ${focusRing.offset};`,
    `  --focus-glow: ${focusRing.glow};`,
  );
  out.push(
    `  --motion-shimmer: ${motion.shimmer};`,
    `  --motion-pulse: ${motion.pulse};`,
    `  --motion-breathe: ${motion.breathe};`,
  );
  out.push("}", "");

  // Responsive type classes: mobile values by default, desktop from 768 up.
  for (const [k, v] of Object.entries(typeScale)) {
    const ls = (s: object) => ("letterSpacing" in s ? ` letter-spacing: ${String(s.letterSpacing)};` : "");
    const fam = (s: { family: string }) => `font-family: var(--font-${s.family});`;
    out.push(
      `.type-${k} { ${fam(v.mobile)} font-size: ${v.mobile.size}px; line-height: ${v.mobile.line}px; font-weight: ${v.mobile.weight};${ls(v.mobile)} }`,
    );
    out.push(
      `@media (min-width: ${breakpoints.md}px) { .type-${k} { font-size: ${v.desktop.size}px; line-height: ${v.desktop.line}px; } }`,
    );
  }
  out.push("");
  return `${out.join("\n")}\n`;
}

if (process.argv[1]?.endsWith("gen-tokens-css.ts")) {
  const target = fileURLToPath(new URL("../apps/web/src/design/tokens.generated.css", import.meta.url));
  writeFileSync(target, buildTokensCss());
  console.log(`wrote ${target}`);
}
